#!/usr/bin/env python3
"""Generate a channel skeleton and its offline contract tests.

The generated files are deliberately small: a single ``search`` action that
uses the standard library only. Replace the stub endpoint and item mapping
with the real site API, then follow docs/ADD-A-SOURCE.md for the remaining
steps (registration, fallback chain, setup, live check).
"""
from __future__ import annotations

import argparse
import keyword
import re
import sys
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parents[1]
CHANNEL_DIR = ROOT / "agent_reach" / "channels"
TEST_DIR = ROOT / "tests"

_NAME_RE = re.compile(r"^[a-z][a-z0-9_]{0,39}$")
_HOST_RE = re.compile(
    r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?"
    r"(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$"
)
_RESERVED_NAMES = {"base", "__init__", "new_channel"}
_MARKER = "Generated by scripts/new_channel.py"

CHANNEL_TEMPLATE = Template(
    '''# -*- coding: utf-8 -*-
# Generated by scripts/new_channel.py; replace the stub endpoint below.
"""$name — $description."""

import json
import urllib.parse
import urllib.request

from agent_reach.runtime.result import BAD_INPUT, NOT_FOUND, ReachError, make_item
from agent_reach.utils.url import host_matches

from .base import Action, Channel, Param

_HOST = $host_literal
_API_BASE = f"https://{_HOST}"
_MAX_RESPONSE_BYTES = 1024 * 1024
_UA = "agent-reach/1.0"


def _validate_api_url(url: str) -> None:
    """Refuse requests outside this channel's HTTPS origin."""
    try:
        parsed = urllib.parse.urlsplit(url)
        port = parsed.port
    except ValueError as exc:
        raise ValueError("invalid API URL") from exc
    if (
        parsed.scheme.lower() != "https"
        or (parsed.hostname or "").lower().rstrip(".") != _HOST
        or port not in {None, 443}
        or parsed.username is not None
        or parsed.password is not None
    ):
        raise ValueError("only this channel's HTTPS API is allowed")


def _get_json(url: str, timeout: float) -> object:
    """Fetch bounded JSON from this channel's origin."""
    _validate_api_url(url)
    request = urllib.request.Request(url, headers={"User-Agent": _UA})
    with urllib.request.urlopen(request, timeout=max(1.0, timeout)) as response:
        raw = response.read(_MAX_RESPONSE_BYTES + 1)
    if len(raw) > _MAX_RESPONSE_BYTES:
        raise ValueError("response exceeds the 1 MiB safety limit")
    return json.loads(raw.decode("utf-8"))


class $class_name(Channel):
    name = $name_literal
    description = $description_literal

    level = "optional"
    actions = (
        Action(
            "search",
            "Search $name",
            (
                Param("query", "what to search for"),
                Param("limit", "max results", required=False, type=int, default=10),
            ),
            (("$name-api", "_api_search"),),
            live_test={"query": "REPLACE_WITH_A_REAL_QUERY", "limit": 2},
        ),
    )

    def can_handle(self, url: str) -> bool:
        return host_matches(url, _HOST)

    def validate_params(self, action: str, params: dict) -> None:
        if action == "search" and not 1 <= params["limit"] <= 50:
            raise ReachError(BAD_INPUT, "limit must be between 1 and 50")

    def _api_search(self, *, query: str, limit: int, timeout: float) -> list:
        # Replace this stub with the site's real endpoint and field mapping.
        url = _API_BASE + "/search?" + urllib.parse.urlencode({"q": query, "limit": limit})
        data = _get_json(url, timeout)
        rows = data.get("items") if isinstance(data, dict) else None
        if not isinstance(rows, list):
            raise ReachError(NOT_FOUND, "the site returned no search results")
        return [
            make_item(
                title=row.get("title"),
                url=row.get("url"),
                author=row.get("author"),
                published_at=row.get("published_at"),
                text=row.get("text"),
                raw=row,
            )
            for row in rows[:limit]
            if isinstance(row, dict)
        ]
'''
)

TEST_TEMPLATE = Template(
    '''# -*- coding: utf-8 -*-
# Generated by scripts/new_channel.py; replace the stub fixture when needed.
"""Contract tests for the generated ``$name`` channel.

These tests never touch the network. Replace the stub fixture when the real
field mapping changes; keep the contract assertions.
"""

import pytest

from agent_reach.channels import $name as module
from agent_reach.channels.$name import $class_name
from agent_reach.runtime.result import ReachError


def test_channel_contract():
    channel = $class_name()
    assert channel.name == $name_literal
    assert channel.description
    assert channel.level in {"default", "optional", "experimental"}
    assert channel.actions
    for action in channel.actions:
        assert action.params
        for label, method in action.backends:
            assert label
            assert callable(getattr(channel, method, None))


def test_can_handle_only_this_site():
    channel = $class_name()
    assert channel.can_handle("https://$host/item/1") is True
    assert channel.can_handle("https://$host.evil.invalid/item/1") is False
    assert channel.can_handle("https://unrelated.invalid/item/1") is False


def test_validate_params_rejects_bad_limit():
    with pytest.raises(ReachError) as caught:
        $class_name().validate_params("search", {"query": "x", "limit": 0})
    assert caught.value.code == "BAD_INPUT"


def test_search_shapes_items_without_network(monkeypatch):
    monkeypatch.setattr(
        module,
        "_get_json",
        lambda url, timeout: {
            "items": [
                {
                    "title": "Example",
                    "url": "https://$host/item/1",
                    "author": "A",
                    "published_at": "2026-01-01T00:00:00Z",
                    "text": "Body",
                }
            ]
        },
    )

    items = $class_name()._api_search(query="x", limit=1, timeout=10)

    assert len(items) == 1
    assert items[0]["title"] == "Example"
    assert items[0]["author"] == "A"
    assert items[0]["text"] == "Body"
    assert items[0]["raw"]["title"] == "Example"
'''
)


def _class_name(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("_")) + "Channel"


def _validate_name(name: str) -> str:
    if not _NAME_RE.fullmatch(name) or keyword.iskeyword(name) or name in _RESERVED_NAMES:
        raise ValueError("name must be a short lowercase identifier such as 'mysite'")
    return name


def _validate_host(host: str) -> str:
    normalized = host.strip().lower().rstrip(".")
    if not _HOST_RE.fullmatch(normalized):
        raise ValueError("host must be a lowercase domain such as 'www.example.com'")
    return normalized


def _validate_class_name(value: str) -> str:
    if not value.isidentifier() or keyword.iskeyword(value):
        raise ValueError("class name must be a valid Python identifier")
    return value


def render_channel(name: str, class_name: str, host: str, description: str) -> str:
    return CHANNEL_TEMPLATE.substitute(
        name=name,
        class_name=class_name,
        host=host,
        description=description,
        name_literal=repr(name),
        host_literal=repr(host),
        description_literal=repr(description),
    )


def render_test(name: str, class_name: str, host: str) -> str:
    return TEST_TEMPLATE.substitute(
        name=name,
        class_name=class_name,
        host=host,
        name_literal=repr(name),
    )


def _is_generated(path: Path) -> bool:
    try:
        return _MARKER in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("name", help="channel name, e.g. mysite")
    parser.add_argument("--host", help="site domain; default: <name>.example")
    parser.add_argument("--class-name", dest="class_name", help="Channel class name")
    parser.add_argument("--description", help="one-line channel description")
    parser.add_argument("--force", action="store_true", help="overwrite existing generated files")
    args = parser.parse_args(argv)

    try:
        name = _validate_name(args.name)
        class_name = _validate_class_name(args.class_name or _class_name(name))
        host = _validate_host(args.host or f"{name.replace('_', '-')}.example")
        description = args.description or f"{name} search"
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    channel_path = CHANNEL_DIR / f"{name}.py"
    test_path = TEST_DIR / f"test_{name}_channel.py"
    existing = [path for path in (channel_path, test_path) if path.exists()]
    if existing and not args.force:
        print("error: refusing to overwrite existing files:", file=sys.stderr)
        for path in existing:
            print(f"  {path.relative_to(ROOT)}", file=sys.stderr)
        print("pass --force to overwrite generated files", file=sys.stderr)
        return 2
    foreign = [path for path in existing if not _is_generated(path)]
    if foreign:
        print("error: refusing to overwrite files not created by this script:", file=sys.stderr)
        for path in foreign:
            print(f"  {path.relative_to(ROOT)}", file=sys.stderr)
        print("move them away first", file=sys.stderr)
        return 2

    CHANNEL_DIR.mkdir(parents=True, exist_ok=True)
    TEST_DIR.mkdir(parents=True, exist_ok=True)
    channel_path.write_text(render_channel(name, class_name, host, description), encoding="utf-8")
    test_path.write_text(render_test(name, class_name, host), encoding="utf-8")

    print("Created:")
    print(f"  {channel_path.relative_to(ROOT)}")
    print(f"  {test_path.relative_to(ROOT)}")
    print()
    print("Register it in agent_reach/channels/__init__.py:")
    print(f"  from .{name} import {class_name}")
    print(f"  ... and add {class_name}() to ALL_CHANNELS.")
    print()
    print("Then run:")
    print(f"  python -m pytest -q tests/test_{name}_channel.py")
    print("See docs/ADD-A-SOURCE.md for the fallback chain, error mapping and pitfalls.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())